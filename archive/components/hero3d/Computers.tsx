/** Brand orange on black, or its inverse — the wall alternates between the two. */
const SCREEN_ORANGE = "#FE4701";
const SCREEN_BLACK = "#000000";
const WORDMARK = "Muse.";

/**
 * Each text screen is a 2D canvas painted once and scrolled by animating the
 * texture offset, not a second 3D scene rendered into a framebuffer.
 *
 * Upstream drew these with drei's <Text>, which is troika-three-text, which
 * builds its glyph-shaping worker by inlining source into a Blob and then
 * calling `importScripts` on more Blob URLs. Under this site's CSP that fails,
 * and it does not fail gracefully — the worker rejects, the exception escapes
 * during render, and the entire react-three-fiber tree unmounts, leaving a
 * black canvas. Allowing `blob:` in `script-src` would fix it by weakening the
 * one directive worth keeping tight.
 *
 * A canvas texture avoids the question and is strictly cheaper anyway: it
 * drops eight live render targets from the frame, needs no font file shipped
 * to `public/`, and — because it paints with the real `--font-space-grotesk`
 * family — puts the brand face on the screens instead of upstream's Inter.
 */
const WORDMARK_TEXTURE_SIZE = 256;

/** The next/font family name, read off the CSS variable the layout sets. */
function brandFontStack(): string {
  const source = document.body ?? document.documentElement;
  const family = getComputedStyle(source).getPropertyValue("--font-space-grotesk").trim();
  return family ? `${family}, sans-serif` : "sans-serif";
}

function paintWordmark(canvas: HTMLCanvasElement, invert: boolean) {
  const ctx = canvas.getContext("2d");
  if (!ctx) return;
  const size = canvas.width;
  ctx.fillStyle = invert ? SCREEN_BLACK : SCREEN_ORANGE;
  ctx.fillRect(0, 0, size, size);
  ctx.fillStyle = invert ? SCREEN_ORANGE : SCREEN_BLACK;
  ctx.font = `700 ${Math.round(size * 0.26)}px ${brandFontStack()}`;
  ctx.textAlign = "center";
  ctx.textBaseline = "middle";
  ctx.fillText(WORDMARK, size / 2, size / 2);
}

/**
 * Builds the texture into a ref and hangs it on the material imperatively,
 * rather than creating it in a `useMemo` and passing it as a `map` prop.
 *
 * three.js objects are mutable by design and this one is mutated constantly —
 * repainted when the webfont lands, scrolled every frame — but React Compiler
 * freezes any value that reaches JSX, so a texture passed as a prop may not
 * legally be touched again. Refs are the supported escape hatch for exactly
 * this: mutable state the renderer owns and React does not.
 */
function useWordmarkTexture(
  materialRef: React.RefObject<THREE.MeshBasicMaterial | null>,
  invert: boolean,
) {
  const textureRef = useRef<THREE.CanvasTexture | null>(null);

  useEffect(() => {
    const canvas = document.createElement("canvas");
    canvas.width = WORDMARK_TEXTURE_SIZE;
    canvas.height = WORDMARK_TEXTURE_SIZE;

    const texture = new THREE.CanvasTexture(canvas);
    // Horizontal repeat is what makes the offset scroll wrap seamlessly; the
    // vertical axis never moves, so it clamps.
    texture.wrapS = THREE.RepeatWrapping;
    texture.wrapT = THREE.ClampToEdgeWrapping;
    texture.colorSpace = THREE.SRGBColorSpace;
    texture.anisotropy = 8;
    textureRef.current = texture;

    const material = materialRef.current;
    if (material) {
      material.map = texture;
      material.needsUpdate = true;
    }

    const draw = () => {
      paintWordmark(canvas, invert);
      texture.needsUpdate = true;
    };
    draw();
    // next/font resolves Space Grotesk asynchronously, so the first paint can
    // land on the fallback face. Repaint once the real one is in.
    let cancelled = false;
    void document.fonts.ready.then(() => {
      if (!cancelled) draw();
    });

    return () => {
      cancelled = true;
      textureRef.current = null;
      texture.dispose();
    };
  }, [materialRef, invert]);

  return textureRef;
}

/** How much of the texture scrolls past per second. Slow — it should read as
 *  ambient movement on a wall, not as something asking to be read. */
const SCROLL_RATE = 0.05;

type ScreenTextProps = Omit<ThreeElements["group"], "children"> & {
  frame: string;
  panel: string;
  invert?: boolean;
  /** Fixes this screen's scroll phase. Upstream drew a fresh `Math.random()`
   *  on every render, so the phase jumped whenever React re-rendered; a stable
   *  per-screen seed staggers the wall without that. */
  seed: number;
};

function ScreenText({ invert = false, seed, frame, panel, ...props }: ScreenTextProps) {
  const { meshes, materials } = useComputersModel();
  const materialRef = useRef<THREE.MeshBasicMaterial>(null);
  const textureRef = useWordmarkTexture(materialRef, invert);

  useFrame((state) => {
    const texture = textureRef.current;
    if (!texture) return;
    texture.offset.x = (seed * 0.137 + state.clock.elapsedTime * SCROLL_RATE) % 1;
  });

  return (
    <group {...props}>
      <mesh castShadow receiveShadow geometry={meshes[frame].geometry} material={materials.Texture} />
      {/* `toneMapped={false}` keeps the screen out of the renderer's tone curve
          so it reads as emitting, and feeds the bloom pass cleanly. The map is
          attached by useWordmarkTexture once the canvas exists. */}
      <mesh geometry={meshes[panel].geometry}>
        <meshBasicMaterial ref={materialRef} toneMapped={false} />
      </mesh>
    </group>
  );
}

/** Flashing status LEDs. The colour is driven per-instance every frame, which
 *  is why they are `MeshBasicMaterial` with tone mapping off — they are meant
 *  to clip and bleed into the bloom pass. */
function Leds() {
  const ref = useRef<THREE.Group>(null);
  const i = useInstances();

  useFrame((state) => {
    if (!ref.current) return;
    for (const child of ref.current.children) {
      const led = child as THREE.Object3D & { color: THREE.Color };
      if (!led.color) continue;
      const rand = Math.abs(2 + led.position.x);
      const t = Math.round((1 + Math.sin(rand * 10000 + state.clock.elapsedTime * rand)) / 2);
      led.color.setRGB(0, t * 1.1, t);
    }
  });

  return (
    <group ref={ref}>
      <i.Sphere position={[-0.41, 1.1, -2.21]} scale={0.005} color={[1, 2, 1]} />
      <i.Sphere position={[0.59, 1.32, -2.22]} scale={0.005} color={[1, 2, 1]} />
      <i.Sphere position={[1.77, 1.91, -1.17]} scale={0.005} color={[1, 2, 1]} />
      <i.Sphere position={[2.44, 1.1, -0.79]} scale={0.005} color={[1, 2, 1]} />
      <i.Sphere position={[4.87, 3.8, -0.1]} scale={0.005} color={[1, 2, 1]} />
      <i.Sphere position={[1.93, 3.8, -3.69]} scale={0.005} color={[1, 2, 1]} />
      <i.Sphere position={[-2.35, 3.8, -3.48]} scale={0.005} color={[1, 2, 1]} />
      <i.Sphere position={[-4.71, 4.59, -1.81]} scale={0.005} color={[1, 2, 1]} />
      <i.Sphere position={[-3.03, 2.85, 1.19]} scale={0.005} color={[1, 2, 1]} />
      <i.Sphere position={[-1.21, 1.73, -1.49]} scale={0.005} color={[1, 2, 1]} />
    </group>
  );
}
