/** The render-prop argument drei hands back from `Merged` — a component per
 *  instanced mesh, keyed by the names given in the `meshes` prop. */
type MergedInstances = Parameters<React.ComponentProps<typeof Merged>["children"]>[0];

const InstanceContext = createContext<MergedInstances | null>(null);

/**
 * A stand-in mesh for the LED spheres, carrying the GLTF's geometry but an
 * unlit, un-tone-mapped material — the LEDs get their colour written per
 * instance every frame and are meant to clip and bleed into the bloom pass.
 *
 * Upstream reassigned `nodes.Sphere.material` in place. That mutates the
 * cached GLTF, which drei shares across every consumer of the URL, and it does
 * it during render. Constructing a separate mesh keeps the loaded model
 * untouched and the render pure; `Merged` only ever reads `.geometry` and
 * `.material` off what it is given, so it cannot tell the difference.
 */
function buildLedMesh(source: THREE.Mesh): THREE.Mesh {
  const material = new THREE.MeshBasicMaterial();
  material.toneMapped = false;
  return new THREE.Mesh(source.geometry, material);
}

function useInstances(): MergedInstances {
  const instances = useContext(InstanceContext);
  if (!instances) throw new Error("<Computers> must be rendered inside <Instances>");
  return instances;
}

